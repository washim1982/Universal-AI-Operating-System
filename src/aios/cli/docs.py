"""``aios docs reference``: the reference pages of the docs site, made from the code (WP 3.6).

The CLI page comes from the command table, the API page from the API's own OpenAPI document, and
the events and manifests pages from the models. ``--check`` fails when a committed page is stale,
so the reference can't drift from what AIOS does.
"""

# pyright: reportPrivateUsage=false
# argparse keeps its command table in classes it marks private; reading them is the only way.

from __future__ import annotations

import argparse
import asyncio
from collections.abc import Mapping
from pathlib import Path
from typing import Any, cast

from aios.core import catalog
from aios.core.schemas import MANIFEST_KINDS, manifest_schema

HEADER = (
    "<!-- Generated by `aios docs reference`. Do not edit: change the code it is made from. -->"
)


def pages(parser: argparse.ArgumentParser) -> dict[str, str]:
    return {
        "cli.md": cli_page(parser),
        "api.md": api_page(),
        "events.md": events_page(),
        "manifests.md": manifests_page(),
    }


def write(folder: Path, parser: argparse.ArgumentParser, *, check: bool) -> list[Path]:
    """Write the pages, or with ``check`` only say which are missing or stale."""
    stale: list[Path] = []
    for name, text in pages(parser).items():
        path = folder / name
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return stale


# ---------------------------------------------------------------------- the CLI


def cli_page(parser: argparse.ArgumentParser) -> str:
    lines = [
        "# Command reference",
        "",
        HEADER,
        "",
        "Every `aios` command. Commands that talk to a server read `AIOS_SERVER` (or `--server`)",
        "and send `AIOS_API_KEY` as the credential; `--tenant` picks a tenant for a platform",
        "administrator.",
        "",
    ]
    for name, command in _subcommands(parser):
        lines += [f"## aios {name}", "", (command.description or _help_of(parser, name)), ""]
        lines += ["```text", _usage(command), "```", ""]
        rows = _arguments(command)
        if rows:
            lines += ["| Argument | Meaning |", "|---|---|", *rows, ""]
        for sub_name, sub in _subcommands(command):
            lines += [f"### aios {name} {sub_name}", "", _help_of(command, sub_name), ""]
            lines += ["```text", _usage(sub), "```", ""]
            sub_rows = _arguments(sub)
            if sub_rows:
                lines += ["| Argument | Meaning |", "|---|---|", *sub_rows, ""]
    return "\n".join(lines).rstrip() + "\n"


def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, argparse.ArgumentParser]]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            choices = cast(Mapping[str, argparse.ArgumentParser], cast(Any, action).choices)
            return sorted(choices.items())
    return []


def _help_of(parser: argparse.ArgumentParser, name: str) -> str:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for choice in action._choices_actions:
                if choice.dest == name and choice.help:
                    return f"{choice.help[0].upper()}{choice.help[1:]}."
    return ""


def _usage(parser: argparse.ArgumentParser) -> str:
    text = parser.format_usage().removeprefix("usage: ").strip()
    return " ".join(text.split())


def _arguments(parser: argparse.ArgumentParser) -> list[str]:
    rows: list[str] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction | argparse._HelpAction):
            continue
        names = ", ".join(f"`{n}`" for n in action.option_strings) or f"`{action.dest}`"
        meaning = (action.help or "").replace("|", "\\|")
        if action.choices and not isinstance(action.choices, Mapping):
            meaning += f" One of: {', '.join(str(c) for c in action.choices)}."
        rows.append(f"| {names} | {meaning.strip()} |")
    return rows


# ---------------------------------------------------------------------- the API


def api_page() -> str:
    document = asyncio.run(_openapi())
    lines = [
        "# API reference",
        "",
        HEADER,
        "",
        "Every route of the AIOS API. Send a credential as `Authorization: Bearer <key or token>`;",
        "a local `aios dev` server needs none. What each caller may do is decided by their roles",
        "(see the user guide). The full OpenAPI document is served at `/openapi.json`.",
        "",
    ]
    paths = cast(Mapping[str, Mapping[str, Any]], document["paths"])
    groups: dict[str, list[str]] = {}
    for path, operations in sorted(paths.items()):
        group = path.split("/")[2] if path.startswith("/v1/") else "service"
        for method, operation in operations.items():
            text = str(operation.get("description") or operation.get("summary") or "").strip()
            first = text.split("\n\n")[0].replace("\n", " ").replace("|", "\\|")
            groups.setdefault(group, []).append(f"| `{method.upper()}` | `{path}` | {first} |")
    for group, rows in sorted(groups.items()):
        lines += [f"## {group}", "", "| Method | Path | What it does |", "|---|---|---|", *rows, ""]
    return "\n".join(lines).rstrip() + "\n"


async def _openapi() -> dict[str, Any]:
    from aios.api import create_app  # noqa: PLC0415 - only this page needs the API
    from aios.testing.runtime import LocalRuntime  # noqa: PLC0415

    async with LocalRuntime() as runtime:
        return create_app(runtime.runtime).openapi()


# ---------------------------------------------------------------------- events and manifests


def events_page() -> str:
    lines = [
        "# Event reference",
        "",
        HEADER,
        "",
        "Every standard event type. Commands end in `requested` and are consumed by exactly one",
        "handler; facts are broadcast. Each payload's JSON Schema is served at",
        "`/v1/schemas/events/<type>`, and committed under `specs/schemas/events/`.",
        "",
        "| Type | Kind | Emitted by | Description |",
        "|---|---|---|---|",
    ]
    for spec in catalog.STANDARD_EVENTS:
        pending = "" if spec.payload else " *(any payload for now)*"
        lines.append(
            f"| `{spec.type}` | {spec.kind.value} | {spec.emitted_by} | "
            f"{spec.description}{pending} |"
        )
    return "\n".join(lines) + "\n"


def manifests_page() -> str:
    lines = [
        "# Manifest reference",
        "",
        HEADER,
        "",
        "What each kind of manifest may say, in `spec`. Manifests are YAML or JSON, one or",
        "several to a file, under an App's `manifests/` and `policies/` folders. The full JSON",
        "Schemas are served at `/v1/schemas/manifests/<kind>`; point an editor at them for",
        "completion.",
        "",
    ]
    for kind in MANIFEST_KINDS:
        schema = manifest_schema(kind) or {}
        definitions = cast(Mapping[str, Any], schema.get("$defs") or {})
        spec_ref = cast(Mapping[str, Any], schema.get("properties", {})).get("spec", {})
        spec = _resolve(spec_ref, definitions)
        lines += [f"## {kind}", "", "| Field | Type | Meaning |", "|---|---|---|"]
        required: set[str] = set(spec.get("required") or ())
        for field, prop in cast(Mapping[str, Any], spec.get("properties") or {}).items():
            meaning = str(
                _resolve(prop, definitions).get("description") or prop.get("description") or ""
            )
            mark = " (required)" if field in required else ""
            lines.append(
                f"| `{field}`{mark} | {_type(prop)} | {meaning.replace('|', '\\|').strip()} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _resolve(schema: Mapping[str, Any], definitions: Mapping[str, Any]) -> Mapping[str, Any]:
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return cast(Mapping[str, Any], definitions.get(ref.rsplit("/", 1)[-1], {}))
    return schema


def _type(schema: Mapping[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    members = cast(list[Mapping[str, Any]], schema.get("anyOf") or [])
    if members:
        return " or ".join(_type(m) for m in members)
    kind = schema.get("type")
    if kind == "array":
        return f"list of {_type(cast(Mapping[str, Any], schema.get('items') or {}))}"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in cast(list[Any], schema["enum"]))
    return str(kind or "any")
