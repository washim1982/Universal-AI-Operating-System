"""ULID identifiers (spec: https://github.com/ulid/spec).

A ULID is 128 bits: a 48-bit millisecond timestamp followed by 80 random bits, written as 26
Crockford base32 characters. ULIDs sort lexicographically by creation time, which keeps event ids,
run ids and dead-letter ids naturally ordered. Ids generated by one process are strictly
increasing, even within the same millisecond.
"""

from __future__ import annotations

import re
import secrets
import threading
import time
from datetime import UTC, datetime, timedelta
from typing import Annotated

from pydantic import StringConstraints

_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
_DECODE = {char: index for index, char in enumerate(_ALPHABET)}
_RANDOM_BITS = 80
_RANDOM_MAX = (1 << _RANDOM_BITS) - 1
_TIMESTAMP_MAX = (1 << 48) - 1

ULID_LENGTH = 26
ULID_PATTERN = r"^[0-7][0-9A-HJKMNP-TV-Z]{25}$"
_ULID_RE = re.compile(ULID_PATTERN)

Ulid = Annotated[str, StringConstraints(pattern=ULID_PATTERN)]
"""A ULID string, for use as a Pydantic field type."""


def _encode(value: int) -> str:
    return "".join(_ALPHABET[(value >> shift) & 0x1F] for shift in range(125, -1, -5))


class UlidGenerator:
    """Thread-safe monotonic ULID source. Use :func:`new_ulid` unless you need your own clock."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._last_ms = -1
        self._last_random = 0

    def new(self, now_ms: int | None = None) -> str:
        with self._lock:
            ms = time.time_ns() // 1_000_000 if now_ms is None else now_ms
            if ms <= self._last_ms:
                # Same millisecond, or the clock moved backwards: stay monotonic.
                ms = self._last_ms
                random = self._last_random + 1
                if random > _RANDOM_MAX:
                    ms += 1
                    random = secrets.randbits(_RANDOM_BITS)
            else:
                random = secrets.randbits(_RANDOM_BITS)
            if ms > _TIMESTAMP_MAX:
                raise OverflowError("ULID timestamp out of range")
            self._last_ms, self._last_random = ms, random
        return _encode(ms << _RANDOM_BITS | random)


_generator = UlidGenerator()


def new_ulid() -> str:
    """Return a new ULID, strictly greater than every ULID this process generated before."""
    return _generator.new()


def is_ulid(value: str) -> bool:
    """Whether ``value`` is a canonical (uppercase) ULID string."""
    return _ULID_RE.fullmatch(value) is not None


def ulid_time(value: str) -> datetime:
    """The creation time encoded in a ULID, as an aware UTC datetime."""
    if not is_ulid(value):
        raise ValueError(f"not a ULID: {value!r}")
    number = 0
    for char in value:
        number = number << 5 | _DECODE[char]
    # Epoch arithmetic rather than fromtimestamp(), which fails for far-future times on Windows.
    return _EPOCH + timedelta(milliseconds=number >> _RANDOM_BITS)


_EPOCH = datetime(1970, 1, 1, tzinfo=UTC)
