"""Generate the versioned specs under ``specs/`` from the Pydantic models (WP 0.3).

The models are the source of truth; the JSON Schemas and the event-catalog page are generated
and committed so that other languages and tools can use them. ``aios specs check`` fails when the
committed files are stale, which CI and pre-commit enforce.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from aios.core import catalog
from aios.core.envelope import Event
from aios.core.manifests import (
    AgentManifest,
    AppManifest,
    EvaluationManifest,
    ModelPolicyManifest,
    PolicyManifest,
    WorkflowManifest,
)

JSON_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"


def _schema(model: type[BaseModel], schema_id: str, title: str | None = None) -> str:
    schema: dict[str, Any] = {
        "$schema": JSON_SCHEMA_DIALECT,
        "$id": schema_id,
        **model.model_json_schema(by_alias=True),
    }
    if title:
        schema["title"] = title
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def _catalog_markdown() -> str:
    lines = [
        "# Standard event catalog v0.1",
        "",
        "<!-- Generated by `aios specs export` from src/aios/core/catalog.py. Do not edit. -->",
        "",
        "Commands end in `requested` and are consumed by exactly one handler. Facts are",
        "broadcast. Events marked *pending* accept any JSON payload until their work package",
        "defines a schema.",
        "",
        "| Type | Kind | Emitted by | Payload schema | Description |",
        "|---|---|---|---|---|",
    ]
    for spec in catalog.STANDARD_EVENTS:
        schema = (
            f"[{spec.type}.v{spec.version}](schemas/events/{spec.type}.v{spec.version}.json)"
            if spec.payload
            else "*pending*"
        )
        route = f" Routed by `{spec.route_by}`." if spec.route_by else ""
        lines.append(
            f"| `{spec.type}` | {spec.kind.value} | {spec.emitted_by} | {schema} | "
            f"{spec.description}{route} |"
        )
    return "\n".join(lines) + "\n"


def render_specs(extra: Mapping[str, str] | None = None) -> dict[str, str]:
    """Every generated file, keyed by its path relative to ``specs/``.

    ``extra`` adds files that layers above ``core`` generate, such as the Cedar schema; the CLI
    passes them in, since ``core`` imports nothing from those layers.
    """
    files = {
        "schemas/envelope.v1.json": _schema(Event, "aios://schemas/envelope/1"),
        "schemas/manifests/agent.v1alpha1.json": _schema(
            AgentManifest, "aios://schemas/manifests/agent/v1alpha1"
        ),
        "schemas/manifests/app.v1alpha1.json": _schema(
            AppManifest, "aios://schemas/manifests/app/v1alpha1"
        ),
        "schemas/manifests/workflow.v1alpha1.json": _schema(
            WorkflowManifest, "aios://schemas/manifests/workflow/v1alpha1"
        ),
        "schemas/manifests/policy.v1alpha1.json": _schema(
            PolicyManifest, "aios://schemas/manifests/policy/v1alpha1"
        ),
        "schemas/manifests/model-policy.v1alpha1.json": _schema(
            ModelPolicyManifest, "aios://schemas/manifests/model-policy/v1alpha1"
        ),
        "schemas/manifests/evaluation.v1alpha1.json": _schema(
            EvaluationManifest, "aios://schemas/manifests/evaluation/v1alpha1"
        ),
        "event-catalog.md": _catalog_markdown(),
    }
    for spec in catalog.STANDARD_EVENTS:
        if spec.payload is not None:
            files[f"schemas/events/{spec.type}.v{spec.version}.json"] = _schema(
                spec.payload, spec.schema_id, title=f"{spec.type} v{spec.version} payload"
            )
    return {**files, **(extra or {})}


MANIFEST_KINDS = {
    "agent": AgentManifest,
    "app": AppManifest,
    "workflow": WorkflowManifest,
    "policy": PolicyManifest,
    "model-policy": ModelPolicyManifest,
    "evaluation": EvaluationManifest,
}


def registry() -> dict[str, Any]:
    """What the schema registry holds (FR-EVT-10): every event type and manifest kind."""
    return {
        "events": [
            {
                "type": spec.type,
                "version": spec.version,
                "kind": spec.kind.value,
                "emitted_by": spec.emitted_by,
                "description": spec.description,
                "route_by": spec.route_by,
                "schema": f"/v1/schemas/events/{spec.type}" if spec.payload else None,
            }
            for spec in catalog.STANDARD_EVENTS
        ],
        "manifests": [
            {"kind": kind, "version": "v1alpha1", "schema": f"/v1/schemas/manifests/{kind}"}
            for kind in MANIFEST_KINDS
        ],
        "envelope": "/v1/schemas/envelope",
    }


def event_schema(event_type: str) -> dict[str, Any] | None:
    """An event type's payload schema, as ``specs/`` holds it; ``None`` for one without."""
    spec = catalog.get(event_type)
    if spec is None or spec.payload is None:
        return None
    text = _schema(spec.payload, spec.schema_id, title=f"{spec.type} v{spec.version} payload")
    return json.loads(text)


def manifest_schema(kind: str) -> dict[str, Any] | None:
    model = MANIFEST_KINDS.get(kind)
    if model is None:
        return None
    return json.loads(_schema(model, f"aios://schemas/manifests/{kind}/v1alpha1"))


def envelope_schema() -> dict[str, Any]:
    return json.loads(_schema(Event, "aios://schemas/envelope/1"))


def _orphans(root: Path, files: dict[str, str]) -> list[Path]:
    """Files under ``schemas/`` that no model generates any more (e.g. a renamed event)."""
    expected = {root / relative for relative in files}
    folder = root / "schemas"
    if not folder.is_dir():
        return []
    return sorted(path for path in folder.rglob("*") if path.is_file() and path not in expected)


def write_specs(root: Path, extra: Mapping[str, str] | None = None) -> list[Path]:
    """Write the generated specs under ``root``, delete orphaned schema files, and return the
    paths that changed."""
    files = render_specs(extra)
    changed: list[Path] = []
    for relative, content in files.items():
        path = root / relative
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        changed.append(path)
    for path in _orphans(root, files):
        path.unlink()
        changed.append(path)
    return changed


def stale_specs(root: Path, extra: Mapping[str, str] | None = None) -> list[Path]:
    """Generated files under ``root`` that are missing, out of date or orphaned."""
    files = render_specs(extra)
    return [
        root / relative
        for relative, content in files.items()
        if not (root / relative).exists()
        or (root / relative).read_text(encoding="utf-8") != content
    ] + _orphans(root, files)
